test("disposable PostgreSQL proves concurrent Create/JOIN 4+4 limits, rejection and funded rejoin", { skip: !dbUrl }, async () => {
  await withFixture(async (sql) => {
    const userId = fixtureUuid(1);
    const pendingBarrier = makeBarrier(8);
    const pendingResults = await Promise.all(
      Array.from({ length: 8 }, (_, index) => createPending(sql, userId, fixtureUuid(100 + index), { barrier: pendingBarrier })),
    );
    assert.equal(pendingResults.filter((result) => result.ok).length, MAX_PENDING_POKER_TABLES);
    assert.equal(pendingResults.filter((result) => !result.ok && result.code === "pending_table_limit").length, 4);
    assert.deepEqual(await countSlots(sql, userId), { active: 0, pending: 4 });

    const fifthPending = await createPending(sql, userId, fixtureUuid(200));
    assert.equal(fifthPending.ok, false);
    assert.equal(fifthPending.code, "pending_table_limit");
    assert.deepEqual(await countArtifacts(sql, fixtureUuid(200)), { tables: 0, states: 0, escrows: 0 });

    const acceptedPending = pendingResults.filter((result) => result.ok).map((result) => result.tableId);
    const firstJoins = await Promise.all(acceptedPending.slice(0, 2).map((tableId) => authoritativeJoin(sql, userId, tableId)));
    assert.equal(firstJoins.filter((result) => result.ok && result.kind === "fresh").length, 2, JSON.stringify(firstJoins));
    assert.deepEqual(await countSlots(sql, userId), { active: 2, pending: 2 });

    const additionalPending = await Promise.all([
      createPending(sql, userId, fixtureUuid(300)),
      createPending(sql, userId, fixtureUuid(301)),
    ]);
    assert.equal(additionalPending.filter((result) => result.ok).length, 2);
    assert.deepEqual(await countSlots(sql, userId), { active: 2, pending: 4 });

    const joinCandidates = acceptedPending.slice(2).concat(additionalPending.filter((result) => result.ok).map((result) => result.tableId));
    const boundedJoinBarrier = makeBarrier(joinCandidates.length);
    const boundedJoins = await Promise.all(joinCandidates.map((tableId) => authoritativeJoin(sql, userId, tableId, { barrier: boundedJoinBarrier })));
    assert.equal(boundedJoins.filter((result) => result.ok && result.kind === "fresh").length, 2);
    assert.equal(boundedJoins.filter((result) => !result.ok && result.code === "active_table_limit").length, 2);
    assert.deepEqual(await countSlots(sql, userId), { active: 4, pending: 2 });

    const fifthJoinTable = fixtureUuid(400);
    assert.equal((await createPending(sql, userId, fifthJoinTable)).ok, true);
    const beforeRejectedJoin = await sql`select count(*)::int as count from public.chips_transactions;`;
    const fifthJoin = await authoritativeJoin(sql, userId, fifthJoinTable);
    assert.equal(fifthJoin.ok, false);
    assert.equal(fifthJoin.code, "active_table_limit");
    const afterRejectedJoin = await sql`select count(*)::int as count from public.chips_transactions;`;
    assert.equal(Number(afterRejectedJoin[0].count), Number(beforeRejectedJoin[0].count));
    assert.equal(Number((await sql`select count(*)::int as count from public.poker_seats where user_id = ${userId} and is_bot = false;`)[0].count), 4);

    const activeTableId = acceptedPending[0];
    const beforeRejoin = await sql`select count(*)::int as seats from public.poker_seats where user_id = ${userId};`;
    const fundedRejoin = await authoritativeJoin(sql, userId, activeTableId);
    assert.deepEqual(fundedRejoin, { ok: true, kind: "rejoin", tableId: activeTableId });
    const afterRejoin = await sql`select count(*)::int as seats from public.poker_seats where user_id = ${userId};`;
    assert.equal(Number(afterRejoin[0].seats), Number(beforeRejoin[0].seats));

    const rollbackTable = fixtureUuid(500);
    const rollback = await createPending(sql, userId, rollbackTable, { failAfterInsert: true });
    assert.equal(rollback.ok, false);
    assert.deepEqual(await countArtifacts(sql, rollbackTable), { tables: 0, states: 0, escrows: 0 });
    const markerRows = await sql`select count(*)::int as count from public.poker_tables where id = ${activeTableId} and has_human_participant is true;`;
    assert.equal(Number(markerRows[0].count), 1, "accepted first JOIN must transfer pending to active and set the marker");
  });
});

