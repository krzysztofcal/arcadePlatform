function makeBarrier(size) {
  let arrived = 0;
  let release;
  const released = new Promise((resolve) => { release = resolve; });
  return async () => {
    arrived += 1;
    if (arrived === size) release();
    await released;
  };
}

function planNodes(node, result = []) {
  if (!node || typeof node !== "object") return result;
  if (typeof node["Node Type"] === "string") result.push(node);
  for (const child of Array.isArray(node.Plans) ? node.Plans : []) planNodes(child, result);
  return result;
}

